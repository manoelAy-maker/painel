create extension if not exists "pgcrypto";

-- Tabela principal usada pelo painel atual de estadias.
create table if not exists public.ldc_estadias (
  id bigint generated by default as identity primary key,
  local_id text not null unique,
  tipo text not null check (tipo in ('lancada', 'a_lancar')),
  filial text not null default 'jatai-go',
  placa text,
  status text,
  prioridade text default 'Normal',
  dados jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_ldc_estadias_filial on public.ldc_estadias(filial);
create index if not exists idx_ldc_estadias_tipo on public.ldc_estadias(tipo);
create index if not exists idx_ldc_estadias_status on public.ldc_estadias(status);
create index if not exists idx_ldc_estadias_updated_at on public.ldc_estadias(updated_at desc);

