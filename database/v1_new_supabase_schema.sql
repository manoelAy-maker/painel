-- Estrutura v2 já usada por captação/motoristas/transportadoras.
create table if not exists public.vl_filiais (
  id text primary key,
  nome text not null,
  cidade text,
  estado text,
  ativa boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.vl_profiles (
  usuario text primary key,
  nome text not null,
  cargo text not null default 'Operador',
  filial_id text references public.vl_filiais(id),
  avatar text,
  foto text,
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.vl_motoristas (
  id uuid primary key default gen_random_uuid(),
  nome text not null,
  telefone text,
  telefone_limpo text unique,
  cidade text,
  observacao text,
  criado_por text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.vl_transportadoras (
  id text primary key,
  nome text not null,
  ativa boolean not null default true,
  criado_por text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.vl_captacoes (
  id uuid primary key default gen_random_uuid(),
  local_id text not null unique,
  motorista_id uuid references public.vl_motoristas(id) on delete set null,
  captador_usuario text,
  filial_id text references public.vl_filiais(id),
  operacao text not null default 'Farelo',
  status text not null default 'contatado',
  observacao text,
  quantidade_cargas integer not null default 1,
  data_captacao timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_vl_captacoes_filial on public.vl_captacoes(filial_id);
create index if not exists idx_vl_captacoes_captador on public.vl_captacoes(captador_usuario);
create index if not exists idx_vl_captacoes_status on public.vl_captacoes(status);

create table if not exists public.vl_motorista_carregamentos (
  id uuid primary key default gen_random_uuid(),
  motorista_id uuid references public.vl_motoristas(id) on delete cascade,
  captacao_id uuid unique references public.vl_captacoes(id) on delete cascade,
  filial_id text references public.vl_filiais(id),
  operacao text,
  captador_usuario text,
  observacao text,
  carregou_em timestamptz not null default now()
);

create table if not exists public.vl_captacao_eventos (
  id uuid primary key default gen_random_uuid(),
  captacao_id uuid references public.vl_captacoes(id) on delete cascade,
  status_anterior text,
  status_novo text,
  usuario text,
  observacao text,
  created_at timestamptz not null default now()
);

create or replace view public.vw_motoristas_que_carregam as
select
  m.id,
  m.nome,
  m.telefone,
  m.telefone_limpo,
  count(c.id)::int as carregamentos,
  max(c.carregou_em) as ultimo_carregamento
from public.vl_motoristas m
left join public.vl_motorista_carregamentos c on c.motorista_id = m.id
group by m.id, m.nome, m.telefone, m.telefone_limpo;

create or replace function public.delete_captacao_completa(p_local_id text)
returns boolean
language plpgsql
as $$
declare
  v_id uuid;
begin
  select id into v_id from public.vl_captacoes where local_id = p_local_id;
  if v_id is null then
    return true;
  end if;
  delete from public.vl_captacao_eventos where captacao_id = v_id;
  delete from public.vl_motorista_carregamentos where captacao_id = v_id;
  delete from public.vl_captacoes where id = v_id;
  return true;
end;
$$;

